CREATE TABLE NT_CABECERA (
    ID_NOTA             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO_ANEXO        VARCHAR2(300),
    CONTRATANTE         VARCHAR2(200),
    CONTRATISTA         VARCHAR2(200),
    NIT_PRESTADOR       VARCHAR2(50),
    REGIONAL            VARCHAR2(100),
    DEPARTAMENTO        VARCHAR2(100),
    MUNICIPIOS          VARCHAR2(250),
    REGIMEN             VARCHAR2(150),
    AMBITO              VARCHAR2(150),
    GRUPO_ETAREO        VARCHAR2(50),
    ESPECIALIDAD        VARCHAR2(100),
    VIGENCIA            DATE,
    CONSECUTIVO         VARCHAR2(100),
    POBLACION           NUMBER(12, 0) NOT NULL,
    PCT_CONTRIBUTIVO    NUMBER(5, 4) DEFAULT 0.78,
    PCT_SUBSIDIADO      NUMBER(5, 4) DEFAULT 0.22,
    CLAUSULAS_JSON      CLOB,
    USUARIO_CREACION    VARCHAR2(100),
    FECHA_CREACION      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE NT_AGRUPADORES (
    ID_AGRUPADOR        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_NOTA             NUMBER NOT NULL REFERENCES NT_CABECERA(ID_NOTA) ON DELETE CASCADE,
    ORDEN               NUMBER(5, 0) NOT NULL,
    NOMBRE_AGRUPADOR    VARCHAR2(250) NOT NULL
);

CREATE TABLE NT_DETALLE_CUPS (
    ID_DETALLE          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_AGRUPADOR        NUMBER NOT NULL REFERENCES NT_AGRUPADORES(ID_AGRUPADOR) ON DELETE CASCADE,
    ORDEN               NUMBER(6, 0) NOT NULL,
    CODIGO_CUPS         VARCHAR2(30) NOT NULL,
    DESCRIPCION         VARCHAR2(500) NOT NULL,
    FRECUENCIA_ANUAL    NUMBER(18, 12) DEFAULT 0 NOT NULL,
    COSTO_MEDIO_EVENTO  NUMBER(18, 4) DEFAULT 0 NOT NULL
);

CREATE INDEX IDX_NT_AGRUP_NOTA ON NT_AGRUPADORES(ID_NOTA, ORDEN);
CREATE INDEX IDX_NT_DET_AGRUP  ON NT_DETALLE_CUPS(ID_AGRUPADOR, ORDEN);